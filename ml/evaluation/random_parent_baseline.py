"""Closed-form random baseline for parent consistency on DataSED events."""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from ml.dataops.textio import read_csv_rows
from ml.taxonomy import Taxonomy, load_taxonomy


@dataclass(frozen=True)
class RandomParentBaseline:
    """Expected consistency of a uniform 28-way subclass head on real coarse events."""

    class_counts: dict[str, int]
    family_sizes: dict[str, int]
    included_events: int
    excluded_events: int
    value: float


def uniform_parent_baseline(class_ids: list[str], taxonomy: Taxonomy) -> RandomParentBaseline:
    """Average k_c/28 only over events whose true coarse class has subclasses."""
    known = set(taxonomy.class_ids)
    unknown = sorted(set(class_ids).difference(known))
    if unknown:
        raise ValueError(f"Unknown DataSED class IDs: {unknown}")
    counts = Counter(class_ids)
    family_sizes = {
        item.class_id: len(item.subclasses) for item in taxonomy.classes if item.subclasses
    }
    selected_counts = {class_id: counts[class_id] for class_id in family_sizes}
    included = sum(selected_counts.values())
    if not included:
        raise ValueError("No DataSED events belong to a coarse class with subclasses")
    excluded = len(class_ids) - included
    numerator = sum(selected_counts[class_id] * family_sizes[class_id] for class_id in family_sizes)
    return RandomParentBaseline(
        class_counts=selected_counts,
        family_sizes=family_sizes,
        included_events=included,
        excluded_events=excluded,
        value=numerator / (included * 28),
    )


def read_datased_event_classes(path: Path) -> tuple[list[str], str]:
    """Read published events robustly because CSVs can be edited on Windows."""
    rows, encoding = read_csv_rows(path)
    class_ids = [row.get("class_id", "") for row in rows]
    if not class_ids or any(not value for value in class_ids):
        raise ValueError(f"DataSED events missing class_id: {path}")
    return class_ids, encoding


def render_random_parent_baseline(
    baseline: RandomParentBaseline, *, source_encoding: str
) -> str:
    """Render the ADR-0006 §7 artifact with event counts, not frame counts."""
    lines = [
        "# Random parent-consistency baseline — DataSED",
        "",
        "> Generated by `python -m scripts.report_run --random-baseline datased`; "
        "this is a closed-form expectation, not a Monte Carlo experiment.",
        "",
        f"- Annotation encoding read: `{source_encoding}`",
        "- Uniform prediction space: 28 DataSEC subclass nodes, unconditioned on coarse.",
        f"- Included events (10 coarse groups with subclasses): **{baseline.included_events}**",
        f"- Excluded events (12 coarse classes without subclasses): **{baseline.excluded_events}**",
        "",
        "| Coarse class | k_c | DataSED events | Contribution k_c / 28 |",
        "|---|---:|---:|---:|",
    ]
    lines.extend(
        f"| `{class_id}` | {baseline.family_sizes[class_id]} | {baseline.class_counts[class_id]} | "
        f"{baseline.family_sizes[class_id] / 28:.6f} |"
        for class_id in sorted(baseline.family_sizes)
    )
    lines += [
        "",
        f"**Uniform-random parent-consistency baseline: {baseline.value:.6f}.**",
        "",
        "The denominator is events, not frames. The true DataSED coarse label only selects "
        "k_c for this baseline; it does not condition the random 28-way subclass draw.",
    ]
    return "\n".join(lines) + "\n"


def write_datased_random_parent_baseline(
    annotation_path: Path, taxonomy_path: Path, output: Path
) -> RandomParentBaseline:
    """Create the reproducible measurement from frozen labels and taxonomy."""
    class_ids, encoding = read_datased_event_classes(annotation_path)
    baseline = uniform_parent_baseline(class_ids, load_taxonomy(taxonomy_path))
    output.parent.mkdir(parents=True, exist_ok=True)
    report = render_random_parent_baseline(baseline, source_encoding=encoding)
    output.write_text(report, encoding="utf-8")
    return baseline
